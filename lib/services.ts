export function getService(slug: string): ServiceData | undefined {
  return services.find((s) => s.slug === slug);
}

/** Порядок в перелинковке «С этим заказывают» — самый смежный первым */
export function relatedServices(currentSlug: string, count = 3): ServiceData[] {
  const order: Record<string, string[]> = {
    "landing-page": ["razrabotka-saitov", "sajt-vizitka", "seo-prodvizhenie"],
    "sajt-vizitka": ["landing-page", "razrabotka-saitov", "seo-prodvizhenie"],
    "razrabotka-saitov": ["seo-prodvizhenie", "avtomatizaciya-biznesa", "landing-page"],
    "seo-prodvizhenie": ["razrabotka-saitov", "landing-page", "avtomatizaciya-biznesa"],
    "avtomatizaciya-biznesa": ["razrabotka-saitov", "seo-prodvizhenie", "landing-page"],
  };
  return (order[currentSlug] ?? services.map((s) => s.slug))
    .filter((s) => s !== currentSlug)
    .slice(0, count)
    .map((s) => getService(s)!)
    .filter(Boolean);
}
