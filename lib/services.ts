export function getService(slug: string): ServiceData | undefined {
  return services.find((s) => s.slug === slug);
}

/** Порядок в перелинковке «С этим заказывают» — самый смежный первым.
 *  Все остальные услуги на каждой странице (запрос владельца: полная перелинковка).
 *  Недостающие после приоритетного порядка добираются автоматически —
 *  при добавлении новой услуги достаточно добавить её в массив services. */
export function relatedServices(currentSlug: string, count = services.length - 1): ServiceData[] {
  const priority: Record<string, string[]> = {
    "landing-page": ["razrabotka-saitov", "avtomatizaciya-biznesa", "sajt-vizitka", "seo-prodvizhenie", "instagram-threads-avtomatizaciya"],
    "sajt-vizitka": ["landing-page", "razrabotka-saitov", "instagram-threads-avtomatizaciya", "seo-prodvizhenie", "avtomatizaciya-biznesa"],
    "razrabotka-saitov": ["seo-prodvizhenie", "avtomatizaciya-biznesa", "landing-page", "sajt-vizitka", "instagram-threads-avtomatizaciya"],
    "seo-prodvizhenie": ["razrabotka-saitov", "landing-page", "avtomatizaciya-biznesa", "sajt-vizitka", "instagram-threads-avtomatizaciya"],
    "avtomatizaciya-biznesa": ["instagram-threads-avtomatizaciya", "razrabotka-saitov", "seo-prodvizhenie", "landing-page", "sajt-vizitka"],
    "instagram-threads-avtomatizaciya": ["avtomatizaciya-biznesa", "sajt-vizitka", "razrabotka-saitov", "seo-prodvizhenie", "landing-page"],
  };
  const explicit = priority[currentSlug] ?? [];
  const rest = services
    .map((s) => s.slug)
    .filter((s) => s !== currentSlug && !explicit.includes(s));
  return [...explicit, ...rest]
    .filter((s) => s !== currentSlug)
    .slice(0, count)
    .map((s) => getService(s)!)
    .filter(Boolean);
}
