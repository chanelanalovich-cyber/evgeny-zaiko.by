/**
 * Данные услуг для посадочных страниц /uslugi/[slug].
 * Каждый slug = кластер семантического ядра (seo/KEYWORD_CORE.md).
 * Тексты уникальные, написаны под свои кластеры запросов — не переиспользовать
 * одинаковые абзацы на разных страницах (риск «малоценных страниц»).
 *
 * Prices and case-proof numbers are real: prices from ServicesSection (owner),
 * case numbers verified via GSC/Metrika API (see seo/SITE_AUDIT_FACTS.md).
 */

export interface ServiceFaq {
  question: string;
  answer: string;
}

export interface ServiceCommercial {
  /** Заголовок блока, например «Заказать сайт» + акцент «цены и сроки» */
  heading: string;
  accent: string;
  /** Форматы работ с ценой и сроком — только реальные значения из оффера */
  rows: { label: string; price: string; term: string }[];
  note: string;
}

export interface ServiceData {
  slug: string;
  /** H1 страницы — с главным ключом кластера */
  title: string;
  /** <title> до 60 символов */
  metaTitle: string;
  /** meta description до 160 символов */
  metaDescription: string;
  /** Короткий лид под H1 */
  lead: string;
  /** Отображаемое имя услуги (крошки, перелинковка) */
  name: string;
  /** Цена из пакетов ServicesSection — единый источник коммерческих данных */
  priceFrom: number;
  priceLabel: string;
  /** Валюта цены (по умолчанию BYN) — для почасовой поддержки в USD */
  priceCurrency?: "BYN" | "USD";
  /** Суффикс метки в hero страницы услуги («под ключ» по умолчанию) */
  heroNote?: string;
  /** Гео-метка в hero («Беларусь» по умолчанию) — для страницы USCA: «США · Канада» */
  heroGeo?: string;
  /** Тип Schema.org для страницы услуги (Service по умолчанию; для USCA — ProfessionalService) */
  schemaType?: "Service" | "ProfessionalService";
  /** areaServed для JSON-LD (по умолчанию Беларусь) */
  areaServed?: { name: string }[];
  /** Что входит — под кластер */
  includes: { title: string; text: string }[];
  /** Этапы работы */
  steps: { title: string; text: string }[];
  /** FAQ 4–6 вопросов — под FAQPage JSON-LD */
  faq: ServiceFaq[];
  /** Кому подходит — секция под лидом */
  forWhom: { title: string; text: string }[];
  /** Развёрнутый текст об услуге — уникальные абзацы (цель 800–1200 слов на страницу) */
  about: string[];
  /** Почему заказывают у меня */
  whyMe: string[];
  /** Кейс-доказательство (цифры проверяемы, см. ProjectsSection) */
  proof: {
    metric: string;
    metricLabel: string;
    project: string;
    domain: string;
    text: string;
  };
  /** Кластер ядра (для внутреннего контроля) */
  cluster: string;
  /** Блок цен и сроков с CTA «Заказать сайт» — на коммерческих услугах */
  commercial?: ServiceCommercial;
}

